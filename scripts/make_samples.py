"""Bundle a few sample images for the app (assets/samples/ + manifest.json).

Chosen from the TEST set after evaluation, so the demo includes an honest mix:
clear pneumonia, clear normal, a borderline case and the two kinds of error
(a false alarm and a missed pneumonia; if every missed pneumonia falls inside
the Inconclusive zone, one of those instead), plus two non-X-ray images to
show the input guard. Each X-ray file is copied from the test folder without
re-encoding (identical pixels) and is first run through the app's own
pipeline, so each title matches what the app really shows.

X-rays: Kermany et al. (2018), CC BY 4.0, redistributed with attribution. Photo: "astronaut" from scikit-image (NASA,
public domain). Document: generated by this script.

Usage (after python -m src.evaluate):
    python scripts/make_samples.py
"""

import json
import shutil
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from src.calibration import softmax_probs  # noqa: E402
from src.predict import LungLensPredictor  # noqa: E402
from src.utils import data_dir, load_config, load_json  # noqa: E402

OUT = ROOT / "assets" / "samples"
KERMANY = "Kermany et al. (2018), Mendeley Data, CC BY 4.0; test-set file {}"
MAX_TRIES = 25  # candidates checked per category before giving up


def main() -> None:
    cfg = load_config()
    metrics = load_json(ROOT / "reports" / "metrics.json")
    t, low, high = metrics["calibration"]["temperature"], metrics["decision"]["low"], metrics["decision"]["high"]
    threshold = metrics["operating_point"]["threshold"]
    predictor = LungLensPredictor.from_files(cfg)
    if predictor.demo_mode:
        sys.exit("make_samples.py needs the trained model (models/lunglens.pt) and reports/metrics.json")

    preds = pd.read_csv(ROOT / "reports" / "predictions.csv")
    test = preds[preds["split"] == "test"].copy()
    test["p"] = softmax_probs(test[["logit_normal", "logit_pneumonia"]].to_numpy(), t)[:, 1]
    rng = np.random.default_rng(cfg["seed"])

    # Pneumonia X-rays scored below the threshold. If none is below the Inconclusive zone, the app never
    # says "normal" for them, so show one that lands in the zone instead of pretending to have a clean miss.
    missed = test[(test.label == 1) & (test.p < threshold)]
    if (missed.p < low).any():
        miss_category = ("Model error: missed pneumonia", missed[missed.p < low], "normal", 1)
    else:
        miss_category = ("Pneumonia scored below the threshold", missed, "inconclusive", 1)
    borderline = test[(test.p >= low) & (test.p <= high) & ~test.path.isin(missed.path)]

    # (title, candidate rows, decision the APP must give on the bundled copy, how many)
    categories = [
        ("Pneumonia (bacterial)", test[(test.label == 1) & test.path.str.contains("bacteria") & (test.p > high)], "pneumonia", 1),
        ("Pneumonia (viral)", test[(test.label == 1) & test.path.str.contains("virus") & (test.p > high)], "pneumonia", 1),
        ("Normal", test[(test.label == 0) & (test.p < low)], "normal", 2),
        ("Borderline case", borderline, "inconclusive", 1),
        ("Model error: false alarm on a normal X-ray", test[(test.label == 0) & (test.p > high)], "pneumonia", 1),
        miss_category,
    ]

    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("sample_*"):  # samples from an earlier run of this script
        old.unlink()
    manifest, k = [], 1
    for title, rows, expected, n in categories:
        rows = rows.sort_values("path")
        order = rng.permutation(len(rows))[:MAX_TRIES]
        accepted = 0
        for i in order:
            if accepted == n:
                break
            row = rows.iloc[i]
            source = data_dir(cfg) / row["path"]
            result = predictor.predict(Image.open(source))
            if result.ood.verdict != "ok" or result.explanation.decision != expected:
                continue  # the app would not show what the title promises; try another one
            name = f"sample_{k:02d}{source.suffix.lower()}"
            shutil.copyfile(source, OUT / name)
            label = "PNEUMONIA" if row["label"] == 1 else "NORMAL"
            manifest.append({"title": f"X-ray {k}: {title}", "file": name, "label": label,
                             "attribution": KERMANY.format(row["path"])})
            print(f"{name:<24} {title:<44} label {label:<9} app: P = {result.probability:.3f} -> {expected}")
            k += 1
            accepted += 1
        if accepted < n:
            print(f"note: only {accepted} of {n} '{title}' examples found ({len(rows)} candidates on the test set)")

    # Two non-X-rays to demonstrate the input guard.
    from skimage import data as skdata

    Image.fromarray(skdata.astronaut()).save(OUT / "not_xray_photo.jpg", quality=90)
    manifest.append({"title": "Not an X-ray: a photo", "file": "not_xray_photo.jpg", "label": None,
                     "attribution": "'astronaut' test image from scikit-image (NASA, public domain)"})
    page = Image.new("L", (850, 1100), 255)
    draw = ImageDraw.Draw(page)
    for y in range(90, 1000, 30):
        draw.text((80, y), "Patient discharge summary - lorem ipsum dolor sit amet, consectetur", fill=20)
    page.save(OUT / "not_xray_document.png")
    manifest.append({"title": "Not an X-ray: a document", "file": "not_xray_document.png", "label": None,
                     "attribution": "generated by scripts/make_samples.py"})
    for item in manifest[-2:]:
        verdict = predictor.predict(Image.open(OUT / item["file"])).ood.verdict
        print(f"{item['file']:<24} {item['title']:<44} input check: {verdict}")

    (OUT / "manifest.json").write_text(json.dumps(manifest, indent=2))
    print(f"wrote {len(manifest)} samples to {OUT.relative_to(ROOT)}/")


if __name__ == "__main__":
    main()
